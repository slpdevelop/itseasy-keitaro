"""FastAPI application factory and lifecycle management."""

import logging
from collections.abc import AsyncGenerator
from contextlib import asynccontextmanager
from typing import cast

import httpx
from fastapi import FastAPI
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from starlette.exceptions import HTTPException as StarletteHTTPException
from starlette.types import ASGIApp

from app.api.endpoints.health import router as health_router
from app.api.v1.router import router as v1_router
from app.core.config import Settings, get_settings
from app.core.database import (
    close_database,
    create_database_engine,
)
from app.core.exceptions import (
    AppError,
    app_exception_handler,
    http_exception_handler,
    unhandled_exception_handler,
    validation_exception_handler,
)
from sqlalchemy.ext.asyncio import AsyncEngine, async_sessionmaker

logger: logging.Logger = logging.getLogger(__name__)


def setup_logging(settings: Settings) -> None:
    """Init logger"""
    logging.basicConfig(
        level=settings.log_level_int,
        format="%(asctime)s %(levelname)s [%(name)s] %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )


@asynccontextmanager
async def lifespan(application: FastAPI) -> AsyncGenerator[None, None]:
    """Own the PostgreSQL connection and one reusable
    HTTP connection pool for the whole application lifespan.
    """
    settings: Settings = application.state.settings

    db_engine: AsyncEngine = create_database_engine(settings)
    application.state.db_engine = db_engine
    application.state.session_factory = async_sessionmaker(
        db_engine,
        expire_on_commit=False,
    )

    client = httpx.AsyncClient(
        base_url=f"{settings.keitaro_base_url.rstrip('/')}/admin_api/v1",
        headers={
            "Api-Key": settings.keitaro_api_token.get_secret_value(),
            "Accept": "application/json",
        },
        timeout=httpx.Timeout(settings.keitaro_timeout_seconds),
    )
    application.state.http_client = client

    logger.info("Starting Keitaro Campaign Manager")
    logger.debug("Environment: %s; debug: %s", settings.env, settings.debug)
    try:
        yield
    finally:
        await client.aclose()
        await close_database(application.state.db_engine)
        application.state.db_engine = None
        logger.info("Shutting down Keitaro Campaign Manager")


def get_app(settings: Settings | None = None) -> ASGIApp:
    """Create the FastAPI application, wrapped so CORS also covers generated 500s."""
    settings = settings or get_settings()
    setup_logging(settings)

    application = FastAPI(
        title=settings.app_name,
        description=settings.app_description,
        version=settings.app_version,
        docs_url="/docs" if settings.env == "development" else None,
        redoc_url=None,
        openapi_url="/openapi.json" if settings.env == "development" else None,
        lifespan=lifespan,
    )
    application.state.settings = settings
    application.dependency_overrides[get_settings] = lambda: settings
    application.include_router(v1_router, prefix="/api")
    application.include_router(health_router)

    application.add_exception_handler(AppError, app_exception_handler)
    application.add_exception_handler(StarletteHTTPException, http_exception_handler)
    application.add_exception_handler(RequestValidationError, validation_exception_handler)
    application.add_exception_handler(Exception, unhandled_exception_handler)

    # This outer wrapper is intentional: an inner CORS middleware cannot add headers
    # to 500 responses generated by Starlette's outer ServerErrorMiddleware.
    return CORSMiddleware(
        app=cast(ASGIApp, application),
        allow_origins=settings.cors_allowed_origins,
        allow_credentials=settings.cors_allow_credentials,
        allow_methods=["*"],
        allow_headers=["*"],
    )
